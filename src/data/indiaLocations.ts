export const getZonesForDistrict = (state?: string, district?: string): string[] => {
  if (district && DISTRICT_ZONES[district]) {
    const list = [...DISTRICT_ZONES[district]];
    if (!list.includes("OTHER ZONE")) list.push("OTHER ZONE");
    return list;
  }
  if (state && STATE_ZONES[state]) {
    const list = [...STATE_ZONES[state]];
    if (!list.includes("OTHER ZONE")) list.push("OTHER ZONE");
    return list;
  }
  return DEFAULT_PAN_INDIA_ZONES;
};

export const getDefaultZoneForDistrict = (state?: string, district?: string): string => {
  const zones = getZonesForDistrict(state, district);
  return zones[0] || "CENTRAL ZONE";
};

export const getDefaultZoneForState = (state?: string): string => {
  if (state && STATE_ZONES[state]) {
    return STATE_ZONES[state][0];
  }
  return "CENTRAL ZONE";
};
